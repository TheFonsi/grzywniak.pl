// Run tests/contract-http.py first. jsdom is a disposable test dependency under tmp.
import { JSDOM } from '../tmp/contract-ui-tests/node_modules/jsdom/lib/api.js';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const html=readFileSync(new URL('../tmp/contract-http/contract-editor.html',import.meta.url),'utf8');
const script=readFileSync(new URL('../api/contract-review.js',import.meta.url),'utf8');
const dom=new JSDOM(html,{runScripts:'outside-only'});
dom.window.eval(script);
const form=dom.window.document.querySelector('form.contract-form');
const api=dom.window.contractReview;
api.init(form);
const daysCard=form.querySelector('[data-review-field="acceptanceDays"]');
const daysInput=form.elements.acceptanceDays;
assert.equal(daysInput.type,'number');
daysCard.querySelector('[data-days="7"]').click();
assert.equal(daysInput.value,'7','Preset writes only a numeric day count');
assert.equal(JSON.parse(form.elements.reviewState.value).acceptanceDays.accepted,false,'Preset is not automatic approval');
daysCard.querySelector('[data-review-accept]').click();
assert.equal(daysCard.querySelector('[data-day-choices]').hidden,true,'Approved field hides presets');
daysCard.querySelector('[data-review-edit]').click();
daysInput.value='91';daysInput.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.equal(daysCard.querySelector('[data-review-accept]').disabled,true,'Invalid day count cannot be approved');
daysCard.querySelector('[data-days="14"]').click();
assert.equal(daysInput.value,'14');
assert.equal(form.elements.rightsInventory.hidden,true,'Inventory uses readable controls');
const inventory=form.querySelector('[data-review-field="rightsInventory"] [data-inventory-editor]');
inventory.querySelector('button').click();
inventory.querySelector('input').value='Custom component';
inventory.querySelector('input').dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.equal(JSON.parse(form.elements.rightsInventory.value)[0].name,'Custom component','Inventory controls persist the component');
assert.equal(JSON.parse(form.elements.reviewState.value).rightsInventory.accepted,false);
const dpaCard=form.querySelector('[data-review-field="processingSubprocessors"]');
form.elements.dataRole.value='processor';form.elements.dataRole.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
assert.equal(dpaCard.hidden,false);
[...dpaCard.querySelectorAll('[data-inventory-editor] button')].find(b=>b.textContent.includes('brak')).click();
assert.equal(form.elements.processingSubprocessors.value,'[]','No-subprocessor choice is explicit');
form.elements.dataRole.value='none';form.elements.dataRole.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
assert.equal(form.querySelector('[data-review-field="requestedTemplateId"]'),null,'Template choice is not a legal fact');
assert.equal(form.querySelector('[data-review-field="consumerDocuments"]').hidden,true);
form.elements.clientType.value='protected';
form.elements.clientType.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
assert.equal(form.querySelector('[data-review-field="consumerDocuments"]').hidden,false);
form.elements.clientType.value='business';
form.elements.clientType.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
assert.ok(form.querySelector('[data-review-field="provider"]'));
assert.ok(form.querySelector('[data-review-field="scope"]'));
api.apply(form,{fields:{support:'Wsparcie przez 30 dni.',provider:'Test Provider'},facts:{ipMode:'exclusive',rightsTerms:'Licencja na 5 lat.',clientAddress:'',productionHosting:'MyDevil'}});
const card=name=>form.querySelector(`[data-review-field="${name}"]`);
assert.equal(card('rightsTerms').hidden,false);
assert.equal(card('clientAddress').querySelector('[data-review-accept]').disabled,true);
card('support').querySelector('[data-review-accept]').click();
assert.equal(JSON.parse(form.elements.reviewState.value).support.accepted,true);
assert.equal(form.elements.support.hidden,true);
assert.equal(card('support').querySelector('[data-review-preview]').textContent,'Wsparcie przez 30 dni.');
let submits=0;
form.addEventListener('submit',event=>{submits++;event.preventDefault();});
const enter=new dom.window.KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true});
form.elements.productionHosting.dispatchEvent(enter);
assert.equal(enter.defaultPrevented,true,'Enter must not submit the full contract form');
assert.equal(JSON.parse(form.elements.reviewState.value).productionHosting.accepted,true,'Enter must accept the active field');
assert.equal(card('productionHosting').dataset.accepted,'1');
assert.equal(submits,0,'Enter on a reviewed field must not trigger another contract action');
api.apply(form,{fields:{support:'Changed by AI'},facts:{}});
assert.equal(form.elements.support.value,'Wsparcie przez 30 dni.');
api.apply(form,{fields:{support:'Wzór sklepu'},facts:{},replaceTemplate:true,template:{id:'ecommerce',title:'Umowa sklepu',revision:1,version:2}});
assert.equal(form.elements.support.value,'Wzór sklepu','Explicit template replacement must replace accepted clauses');
assert.equal(form.elements.templateId.value,'ecommerce');
assert.equal(form.elements.templateVersion.value,'2');
assert.equal(JSON.parse(form.elements.reviewState.value).support.accepted,false);
card('support').querySelector('[data-review-edit]').click();
assert.equal(form.elements.support.hidden,false);
form.elements.support.value='Wsparcie przez 60 dni.';
form.elements.support.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.equal(JSON.parse(form.elements.reviewState.value).support.accepted,false);
card('support').querySelector('[data-review-accept]').click();
const reopened=new JSDOM(html,{runScripts:'outside-only'});
reopened.window.eval(script);
const reopenedForm=reopened.window.document.querySelector('form.contract-form');
reopenedForm.elements.reviewState.value=form.elements.reviewState.value;
reopenedForm.elements.support.value=form.elements.support.value;
reopened.window.contractReview.init(reopenedForm);
assert.equal(reopenedForm.querySelector('[data-review-field="support"]').dataset.accepted,'1');
form.elements.ipMode.value='transfer';
form.elements.ipMode.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
assert.equal(card('rightsTerms').hidden,true);
form.elements.publicationDestination.value='agency_purchase';
form.elements.publicationDestination.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
for(const name of ['productionDomain','domainRegistrar','domainRegistrant','domainRenewalTerms','hostingFee']) assert.equal(card(name).hidden,false,`${name} visible for managed domain purchase`);
assert.equal(card('productionHosting').hidden,true,'Customer server details excluded');
form.elements.publicationDestination.value='agency';
form.elements.publicationDestination.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
assert.equal(card('domainRegistrant').hidden,true,'Domain procurement hidden for agency subdomain');
console.log('Contract UI checks passed, including managed domain purchase visibility.');
