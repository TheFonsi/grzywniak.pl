// Run tests/contract-http.py first. jsdom is a disposable test dependency under tmp.
import { JSDOM } from '../tmp/contract-ui-tests/node_modules/jsdom/lib/api.js';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const html=readFileSync(new URL('../tmp/contract-http/contract-editor.html',import.meta.url),'utf8');
const script=readFileSync(new URL('../api/contract-review.js',import.meta.url),'utf8');
const dom=new JSDOM(html,{runScripts:'outside-only'});
dom.window.eval(script);
const form=dom.window.document.querySelector('form.contract-form');
const api=dom.window.contractReview;
api.init(form);
assert.ok(form.querySelector('[data-review-field="provider"]'));
assert.ok(form.querySelector('[data-review-field="scope"]'));
api.apply(form,{fields:{support:'Wsparcie przez 30 dni.',provider:'Test Provider'},facts:{ipMode:'exclusive',rightsTerms:'Licencja na 5 lat.',clientAddress:''}});
const card=name=>form.querySelector(`[data-review-field="${name}"]`);
assert.equal(card('rightsTerms').hidden,false);
assert.equal(card('clientAddress').querySelector('[data-review-accept]').disabled,true);
card('support').querySelector('[data-review-accept]').click();
assert.equal(JSON.parse(form.elements.reviewState.value).support.accepted,true);
assert.equal(form.elements.support.hidden,true);
assert.equal(card('support').querySelector('[data-review-preview]').textContent,'Wsparcie przez 30 dni.');
api.apply(form,{fields:{support:'Changed by AI'},facts:{}});
assert.equal(form.elements.support.value,'Wsparcie przez 30 dni.');
card('support').querySelector('[data-review-edit]').click();
assert.equal(form.elements.support.hidden,false);
form.elements.support.value='Wsparcie przez 60 dni.';
form.elements.support.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
assert.equal(JSON.parse(form.elements.reviewState.value).support.accepted,false);
card('support').querySelector('[data-review-accept]').click();
const reopened=new JSDOM(html,{runScripts:'outside-only'});
reopened.window.eval(script);
const reopenedForm=reopened.window.document.querySelector('form.contract-form');
reopenedForm.elements.reviewState.value=form.elements.reviewState.value;
reopenedForm.elements.support.value=form.elements.support.value;
reopened.window.contractReview.init(reopenedForm);
assert.equal(reopenedForm.querySelector('[data-review-field="support"]').dataset.accepted,'1');
form.elements.ipMode.value='transfer';
form.elements.ipMode.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
assert.equal(card('rightsTerms').hidden,true);
console.log('Contract UI: accept, edit, changed-value invalidation, accepted-value preservation, reopen, missing facts and license visibility passed.');
